public class Eg2Variaveis {

    public static void main(String[] args) {

        // declaração de variáveis
        int idade;
        String turma = "Turma A";
        double preco = 9.99;

        // caractere explícito
        char letra = 'a';

        // caractere pelo código ASCII
        char letra2 = 66;

        // caractere pelo código Unicode
        char letra3 = '\uA78D';

        // atribuir valor à variável
        idade = 10;

        // utilização das variáveis
        System.out.println("\u058EVariáveis\u058E");
        System.out.println(idade);
        System.out.println(turma);
        System.out.println(preco);
        System.out.println(letra);
        System.out.println(letra2);
        System.out.println(letra3);
    }
}